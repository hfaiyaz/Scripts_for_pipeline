#!/usr/bin/env python3

"""Runs the MEGAHIT assembler on a provided file of reads."""

import my_utils
from pathlib import Path

def _megahit_assembly(self):
        """Runs the MEGAHIT assembly."""
        megahit_out = Path(str(self.DIR) + "/" + self._accession)
        if self._paired:
            mh_1, mh_2 = self.get_files(self.bloom_out)
            my_mh_cmd = [
                "megahit",
                "-1",mh_1,
                "-2",mh_2,
                "-t",str(self.cores),
                "-o",megahit_out
            ]
        else:
            mh_fq = self.get_files(self.bloom_out)
            my_mh_cmd = [
                "megahit",
                "-r",mh_fq,
                "-t",str(self.cores),
                "-o",megahit_out
            ]

        result_mh = my_utils.run_command(
            my_mh_cmd,
            step="MEGAHIT assembly",
            check_state=True
            )

        return result_mh

def _delete_folder_subcontents(self,dir_path:str|None=None,exclude:str="final.contigs.fa"):
        """Deletes subfolder contents generated by MEGAHIT."""
        if dir_path is None:
            dir_path = Path(str(self.DIR) + "/" + self._accession + "/.")
        my_mh_delete_cmd = [
            "find",
            dir_path,
            "-mindepth",
            "1",
            "-not",
            "-name",
            exclude,
            "-delete"
        ]
        mh_delete = my_utils.run_command(my_mh_delete_cmd,
                                step="Megahit delete",
                                check_state=True)
        return mh_delete